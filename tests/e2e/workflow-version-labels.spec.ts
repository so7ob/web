import { expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { test } from './workflow-version-fixture';
test.use({ contextOptions: { reducedMotion: 'reduce' } });
for (const locale of ['ar', 'en'] as const) {
  const t = (ar: string, en: string) => locale === 'ar' ? ar : en;
  test(`${locale}: published version identity remains stable after more publications and scope filtering`, async ({ page, versions }, info) => {
    const select = page.getByRole('combobox', { name: t('الإصدار الهدف', 'Target version'), exact: true });
    await page.goto(`/${locale}/admin/workflows`);
    await page.getByRole('tab', { name: t('نقل المعاملات', 'Transfer conversations'), exact: true }).click();
    const firstOption = select.locator(`option[value="${versions.first}"]`);
    const label = (await firstOption.textContent())!;
    expect(label).toContain(versions.first); expect(label).toContain('UTC');
    const original = await versions.db.query('SELECT id,workflowId,definition,createdAt FROM WorkflowVersion WHERE id=?', [versions.first]);
    const added = await versions.addVersions();
    await page.reload();
    await page.getByRole('tab', { name: t('نقل المعاملات', 'Transfer conversations'), exact: true }).click();
    await expect(firstOption).toHaveText(label);
    const labels = [label];
    for (const id of [added.second, added.other]) {
      const text = (await select.locator(`option[value="${id}"]`).textContent())!;
      expect(text).toContain(id); labels.push(text);
    }
    expect(new Set(labels).size).toBe(3);
    const scope = page.getByRole('combobox', { name: t('نوع المعاملة', 'Conversation type'), exact: true });
    await scope.selectOption('inquiries'); await expect(firstOption).toHaveCount(0);
    await scope.selectOption('requests'); await expect(firstOption).toHaveText(label);
    await select.focus(); await expect(select).toBeFocused();
    await page.keyboard.press('Home'); await page.keyboard.press('ArrowDown');
    await expect(select).not.toHaveValue('');
    await select.selectOption({ label }); await expect(select).toHaveValue(versions.first);
    await expect(select).toHaveAccessibleDescription(label);
    await expect(page.getByRole('note', { name: t('هوية الإصدار المحدد', 'Selected version identity') })).toHaveText(label);
    expect(await versions.db.query('SELECT id,workflowId,definition,createdAt FROM WorkflowVersion WHERE id=?', [versions.first])).toEqual(original);
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await info.attach('stable-version-labels', { body: JSON.stringify({ firstVersion: versions.first, labels, originalVersionUnchanged: true }, null, 2), contentType: 'application/json' });
    await info.attach('version-selection', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' });
  });
  test(`${locale}: real transfer shows the selected destination in preview, confirmation, result and immutable history`, async ({ page, versions }, info) => {
    const { second, other } = await versions.addVersions();
    const versionRows = () => versions.db.query('SELECT id,workflowId,definition,legacy,createdAt FROM WorkflowVersion WHERE id IN (?,?,?) ORDER BY id', [versions.first, second, other]);
    const beforeVersions = await versionRows();
    const beforeEvents = await versions.db.query('SELECT * FROM WorkflowEvent WHERE recordId=? ORDER BY id', [versions.record]);
    await page.goto(`/${locale}/admin/workflows`);
    await page.getByRole('tab', { name: t('نقل المعاملات', 'Transfer conversations'), exact: true }).click();
    const select = page.getByRole('combobox', { name: t('الإصدار الهدف', 'Target version'), exact: true });
    const label = (await select.locator(`option[value="${second}"]`).textContent())!;
    expect(label).toContain(second);
    await select.selectOption({ label });
    await page.getByRole('textbox', { name: t('البحث عن معاملة', 'Find conversation'), exact: true }).fill(versions.ref);
    await page.getByRole('button', { name: t('تحميل المعاملات', 'Load conversations'), exact: true }).click();
    await page.getByRole('checkbox', { name: versions.ref, exact: true }).check();
    await page.getByRole('combobox', { name: t('ربط المرحلة', 'Map stage') + ' new', exact: true }).selectOption('in_review');
    const previewed = page.waitForResponse(r => r.url().endsWith('/workflows/transfer/preview') && r.request().method() === 'POST');
    await page.getByRole('button', { name: t('معاينة النقل', 'Preview transfer'), exact: true }).focus();
    await page.keyboard.press('Enter');
    const response = await previewed; expect(response.status()).toBe(201);
    expect(response.request().postDataJSON().payload.versionId).toBe(second);
    const preview = await response.json(); expect(preview.rows[0].versionId).toBe(versions.first);
    await expect(page.getByRole('note', { name: t('وجهة النقل المعاين', 'Preview destination') })).toHaveText(label);
    const confirm = page.getByRole('button', { name: t('تأكيد النقل المعاين', 'Confirm previewed transfer'), exact: true });
    await expect(confirm).toHaveAccessibleDescription(label);
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([]);
    const confirmed = page.waitForResponse(r => r.url().endsWith('/workflows/transfer/confirm') && r.request().method() === 'POST');
    await confirm.focus(); await page.keyboard.press('Enter');
    const confirmation = await confirmed; expect(confirmation.status()).toBe(201);
    expect(confirmation.request().postDataJSON().payload).toEqual({ previewId: preview.previewId });
    await expect(page.getByRole('status', { name: t('نتيجة النقل', 'Transfer result') })).toContainText(label);
    expect(await versions.db.query("SELECT versionId,stageId FROM ConversationWorkflow WHERE scope='requests' AND recordId=?", [versions.record])).toEqual([{ versionId: second, stageId: 'in_review' }]);
    expect(await versionRows()).toEqual(beforeVersions);
    const events = await versions.db.query('SELECT * FROM WorkflowEvent WHERE recordId=? ORDER BY id', [versions.record]);
    expect(events.filter((event: { id: string }) => beforeEvents.some((old: { id: string }) => old.id === event.id))).toEqual(beforeEvents);
    const transferEvents = events.filter((event: { operationId: string }) => event.operationId === 'transfer-' + preview.previewId);
    expect(transferEvents).toHaveLength(1); expect(transferEvents[0].versionId).toBe(second);
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await info.attach('confirmed-version-identity', { body: JSON.stringify({ sourceVersion: versions.first, destinationVersion: second, label, previewId: preview.previewId, historyVersion: transferEvents[0].versionId, publishedVersionsUnchanged: true }, null, 2), contentType: 'application/json' });
    await info.attach('transfer-result', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' });
  });
}
